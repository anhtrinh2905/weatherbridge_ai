/**
 * Rasterize the boundary ring into a per-pixel inside/outside mask using an
 * even–odd scanline fill. Runs once per raster size (cheap: H × edges).
 */
export function buildBoundaryMask(width: number, height: number): Uint8Array {
  const mask = new Uint8Array(width * height);
  const n = BOUNDARY.length;

  for (let y = 0; y < height; y += 1) {
    const py = (y + 0.5) / height;
    const xs: number[] = [];
    for (let e = 0; e < n; e += 1) {
      const [x1, y1] = BOUNDARY[e];
      const [x2, y2] = BOUNDARY[(e + 1) % n];
      if (y1 <= py === y2 <= py) continue;
      xs.push(x1 + ((py - y1) / (y2 - y1)) * (x2 - x1));
    }
    xs.sort((a, b) => a - b);
    for (let s = 0; s + 1 < xs.length; s += 2) {
      const from = Math.max(0, Math.ceil(xs[s] * width - 0.5));
      const to = Math.min(width - 1, Math.floor(xs[s + 1] * width - 0.5));
      for (let x = from; x <= to; x += 1) mask[y * width + x] = 1;
    }
  }
  return mask;
}
